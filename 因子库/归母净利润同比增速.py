import pandas as pd

# 财务因子列：此列表用于存储财务因子相关的列名称󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
fin_cols = ["R_np_atoopc@xbx_单季同比"]  # 财务因子列，配置后系统会自动加载对应的财务数据󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿


def add_factor(df: pd.DataFrame, param=None, **kwargs) -> pd.DataFrame:
    """
    计算归母净利润同比增速的滚动变化，并返回包含因子列的 DataFrame。

    工作流程：
    1. 将 ``param`` 作为滚动间隔；小于 60 时重置为 60，避免窗口过短。
    2. 对单季归母净利润同比字段计算指定间隔的差值。

    :param df: 单只股票的日线数据，需包含 ``R_np_atoopc@xbx_单季同比`` 列。
    :param param: 计算差值使用的交易日间隔。
    :param kwargs: 其他参数，其中 ``col_name`` 为输出因子列名。
    :return: 只包含新因子列的 DataFrame，行数和索引与输入 df 一致。

    注意：所需财务字段由 ``fin_cols`` 声明，框架会在计算前自动合并。
    """

    # ======================== 参数处理 ===========================󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    # 从kwargs中提取因子列的名称，这里使用'col_name'来标识因子列名称󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    col_name = kwargs["col_name"]
    n = int(param)  # 滚动周期数，用于归母净利润同比增速计算󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    if n < 60:
        print(f"⚠️ 滚动周期数{n}小于60，计算结果可能不准确，已经被重置为60")
        n = 60

    # ======================== 计算因子 ===========================󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    # 计算归母净利润同比增速󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    df[col_name] = df["R_np_atoopc@xbx_单季同比"].diff(n)

    return df[[col_name]]
