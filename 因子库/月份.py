import pandas as pd

# 财务因子列：此列表用于存储财务因子相关的列名称󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
fin_cols = []  # 财务因子列，配置后系统会自动加载对应的财务数据󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿


def add_factor(df: pd.DataFrame, param=None, **kwargs) -> pd.DataFrame:
    """
    计算指定月份的标记因子，并返回包含因子列的 DataFrame。

    工作流程：
    1. 将 ``param`` 转换为需要标记的月份列表。
    2. 交易日期命中指定月份时因子值为 1，否则为 0。

    :param df: 单只股票的日线数据，需包含 datetime 类型的 ``交易日期`` 列。
    :param param: 需要标记的月份集合，例如 ``[1, 5, 10]``。
    :param kwargs: 其他参数，其中 ``col_name`` 为输出因子列名。
    :return: 只包含新因子列的 DataFrame，行数和索引与输入 df 一致。
    """

    # ======================== 参数处理 ===========================󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    # 从kwargs中提取因子列的名称，这里使用'col_name'来标识因子列名称󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    col_name = kwargs["col_name"]
    months = list(param)

    # ======================== 计算因子 ===========================󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    # 当交易日所在月份命中指定月份时标记为 1，否则为 0󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    df[col_name] = 0
    df.loc[df["交易日期"].dt.month.isin(months), col_name] = 1

    return df[[col_name]]
