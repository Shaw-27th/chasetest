import pandas as pd

# 财务因子列：此列表用于存储财务因子相关的列名称󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
fin_cols = []  # 财务因子列，配置后系统会自动加载对应的财务数据󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿


def add_factor(df: pd.DataFrame, param=None, **kwargs) -> pd.DataFrame:
    """
    计算最近 N 个交易日的平均换手率，并返回包含因子列的 DataFrame。

    工作流程：
    1. 使用成交额除以流通市值，得到每日换手率。
    2. 对每日换手率计算 ``param`` 日滚动均值。

    :param df: 单只股票的日线数据，需包含 ``成交额`` 和 ``流通市值`` 列。
    :param param: 滚动窗口长度，单位为交易日。
    :param kwargs: 其他参数，其中 ``col_name`` 为输出因子列名。
    :return: 只包含新因子列的 DataFrame，行数和索引与输入 df 一致。
    """

    # ======================== 参数处理 ===========================󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    # 从kwargs中提取因子列的名称，这里使用'col_name'来标识因子列名称󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    col_name = kwargs["col_name"]
    # ======================== 计算因子 ===========================󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    # 计算每日换手率，并取最近 param 个交易日的平均值󠀂󠁥󠀵󠁡󠁥󠀸󠀷󠀲󠀰󠀳󠀱󠀳󠀷󠀳󠀹󠀳󠀷󠀳󠀷󠀳󠀰󠁿
    turnover_rate = df["成交额"] / df["流通市值"]
    df[col_name] = turnover_rate.rolling(param).mean()

    return df[[col_name]]
